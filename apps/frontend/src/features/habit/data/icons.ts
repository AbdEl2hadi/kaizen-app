export const ALL_ICONS = ICON_CATEGORIES.flatMap((c) => c.icons.map((i) => i.name))

/** Search every icon by name or keyword (case-insensitive). */
export function searchIcons(
  query: string
): { name: string; icon: LucideIcons.IconComponent; keywords: string[] }[] {
  const q = query.trim().toLowerCase()
  if (!q) return []
  return ICON_CATEGORIES.flatMap((c) => c.icons).filter(
    (i) => i.name.toLowerCase().includes(q) || i.keywords.some((k) => k.includes(q))
  )
}
